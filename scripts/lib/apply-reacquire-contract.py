#!/usr/bin/env python3
"""Compare the controlled fixture's generated Compose bytes without rewriting evidence.

This is a lexical generated-output contract, not a general YAML parser. The
converter owns document validity. Admit only its narrow one-service/one-volume
fixture envelope and the two reviewed ordinary-network spellings; all other
bytes remain opaque and must compare exactly. No third-party runtime is needed.
"""

import os
from pathlib import Path
import re
import stat
import sys


LIMIT = 8 * 1024 * 1024
FAILURE = "Apply/reacquire fixed point failed: Podman-to-Compose source/target contract."


def generated_envelope(raw):
    text = raw.decode("utf-8")
    if not text.endswith("\n") or any(ord(value) < 32 and value != "\n" for value in text):
        raise ValueError("noncanonical generated bytes")
    lines = text.split("\n")[:-1]
    if lines and lines[0] == "---":
        lines = lines[1:]
    sections, children = [], {}
    current = None
    for line in lines:
        if not line:
            raise ValueError("unexpected generated blank line")
        if not line.startswith(" "):
            if re.fullmatch(r"name: [A-Za-z0-9][A-Za-z0-9_.-]*", line):
                key = "name"
            elif line in ("services:", "networks:", "volumes:"):
                key = line[:-1]
            else:
                # This also rejects directives, further document markers, quoted
                # top-level keys, unknown fields, and scalar/flow mapping ambiguity.
                raise ValueError("unreviewed generated top-level shape")
            if key in sections:
                raise ValueError("duplicate generated top-level key")
            sections.append(key)
            children[key] = set()
            current = key
            continue
        indentation = len(line) - len(line.lstrip(" "))
        if current not in ("services", "networks", "volumes") or indentation % 2:
            raise ValueError("ambiguous generated mapping")
        content = line[indentation:]
        if indentation == 2:
            match = re.fullmatch(r"([A-Za-z0-9][A-Za-z0-9_.-]*):(?: \{\})?", content)
            if match is None or (current == "services" and content.endswith(" {}")):
                raise ValueError("unreviewed generated resource mapping")
            key = match[1]
            if key in children[current]:
                raise ValueError("duplicate generated resource key")
            children[current].add(key)
        elif not children[current] or not re.fullmatch(r"(?:[A-Za-z_][A-Za-z0-9_.-]*:(?: .*)?|- .+)", content):
            raise ValueError("unreviewed generated nested shape")
    if sections != ["name", "services", "networks", "volumes"] or any(
        len(children.get(key, ())) != 1 for key in ("services", "networks", "volumes")
    ):
        raise ValueError("missing or extra generated fixture resource")


def normalized(path, network):
    descriptor = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(descriptor, "rb") as stream:
        if not stat.S_ISREG(os.fstat(stream.fileno()).st_mode):
            raise ValueError("nonregular artifact")
        raw = stream.read(LIMIT + 1)
    if not raw or len(raw) > LIMIT:
        raise ValueError("unbounded artifact")
    generated_envelope(raw)
    # Only these exact generated spellings are admitted. No other whitespace, comments,
    # properties or bytes are normalized, even inside this one network declaration.
    section = re.compile(rb"(?m)^networks:\n  " + re.escape(network.encode())
                         + rb":(?: \{\}\n|\n    internal: false\n)(?=\Z|[^ \t\r\n])")
    if len(section.findall(raw)) != 1:
        raise ValueError("unreviewed network representation")
    return section.sub(b"networks:\n  controlled-ordinary-network: {}\n", raw, count=1)


def main():
    try:
        if len(sys.argv) != 4 or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,255}", sys.argv[3]):
            raise ValueError("invalid invocation")
        source, target, network = sys.argv[1:]
        if normalized(Path(source), network) != normalized(Path(target), network):
            raise ValueError("unrelated artifact drift")
    except (OSError, UnicodeError, ValueError, TypeError):
        raise SystemExit(FAILURE) from None


if __name__ == "__main__":
    main()
